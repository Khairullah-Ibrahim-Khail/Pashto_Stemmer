def build_irregular_map() -> Dict[str, str]:
    """Flatten all paradigms into a single {surface: lemma} dictionary."""
    flat: Dict[str, str] = {}
    for paradigm in _VERB_PARADIGMS.values():
        flat.update(paradigm)
    return flat


# Public flat map used by the stemmer.
IRREGULAR_VERBS: Dict[str, str] = build_irregular_map()

